SELECT category, COUNT(*) AS total_items, ROUND(AVG(price),2) AS avg_price,
       SUM(price * stock_quantity) AS stock_value
FROM grocery_items GROUP BY category HAVING SUM(stock_quantity) > 20 ORDER BY stock_value DESC;

SELECT g.item_name, g.brand_name, g.category, g.price FROM grocery_items g
WHERE g.price > (SELECT AVG(price) FROM grocery_items WHERE category = g.category)
ORDER BY g.category, g.price DESC;

SELECT item_name, brand_name, category, price, expiry_date,
       RANK() OVER (PARTITION BY category ORDER BY price DESC) AS price_rank
FROM grocery_items WHERE expiry_date < '2027-07-01';
